local M = dofile("tests/wow_mock.lua")
local total = 0
local function test(name, callback)
    callback()
    total = total + 1
    print("PASS " .. name)
end
local function hover(id, name)
    M.item(GameTooltip, name or "Hearthstone", id or 6948)
    M.flush()
end
local function panel(A) return A.Tooltips.states[GameTooltip].panel end

test("startup has no data load or profiling", function()
    local A = M.boot()
    assert(A.UI.launcher and M.loads == 0 and M.clockCalls == 0)
end)
test("numeric ID lookup and bilingual card, original untouched", function()
    local A = M.boot()
    hover()
    assert(M.loads == 1 and panel(A).right:GetText() == "炉石")
    assert(panel(A).left:GetText() == "Hearthstone" and GameTooltip:GetItem() == "Hearthstone")
    assert(M.clockCalls == 0)
end)
test("modern and legacy item hooks independently work", function()
    for _, options in ipairs({ {modernOnly=true}, {legacyOnly=true} }) do
        local A = M.boot(options)
        hover()
        assert(panel(A).right:GetText() == "炉石")
    end
end)
test("coalescing and visible repeat skip lookup", function()
    local A = M.boot()
    A.Diagnostics.enabled = true
    M.item(GameTooltip, "Hearthstone", 6948)
    assert(#M.queue == 1)
    M.flush()
    for i=1,20 do A.Tooltips:Queue(A.Tooltips.states[GameTooltip]) end
    assert(#M.queue == 1)
    M.flush()
    assert(A.Diagnostics.metrics.lookup.count == 1)
    assert(A.Diagnostics.metrics.repeat_skipped.count == 1)
end)
test("disabled and pvp have no lookup or queued work", function()
    local A = M.boot()
    A.SetEnabled(false)
    for i=1,100 do M.item(GameTooltip, "Hearthstone", 6948) end
    assert(M.loads == 0 and #M.queue == 0 and M.clockCalls == 0)
    A.SetMode("pvp"); A.SetEnabled(true)
    hover()
    assert(M.loads == 0 and panel(A) == nil)
end)
test("old callbacks cannot resurrect disabled or changed content", function()
    local A = M.boot()
    M.item(GameTooltip, "Hearthstone", 6948)
    A.SetEnabled(false)
    M.flush()
    assert(panel(A) == nil and M.loads == 0)
    A.SetEnabled(true)
    M.item(GameTooltip, "Linen Cloth", 2589)
    M.flush()
    assert(panel(A).right:GetText() == "亚麻布")
end)
test("hide, nonitem and missing translation clear owned display", function()
    local A = M.boot()
    hover()
    hover(117, "Tough Jerky")
    assert(not panel(A):IsShown())
    hover()
    -- Cleared content that is not refilled with an item goes on the re-check.
    GameTooltip:Fire("OnTooltipCleared")
