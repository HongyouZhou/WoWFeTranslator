local M = dofile("tests/wow_mock.lua")
local total = 0
local function test(name, callback)
    callback()
    total = total + 1
    print("PASS " .. name)
end
local function hover(id, name)
    M.item(GameTooltip, name or "Hearthstone", id or 6948)
    M.flush()
end
local function panel(A) return A.Tooltips.states[GameTooltip].panel end

test("startup has no data load or profiling", function()
    local A = M.boot()
    assert(A.UI.launcher and M.loads == 0 and M.clockCalls == 0)
end)
test("numeric ID lookup and bilingual card, original untouched", function()
    local A = M.boot()
    hover()
    assert(M.loads == 1 and panel(A).right:GetText() == "炉石")
    assert(panel(A).left:GetText() == "Hearthstone" and GameTooltip:GetItem() == "Hearthstone")
    assert(M.clockCalls == 0)
end)
test("modern and legacy item hooks independently work", function()
    for _, options in ipairs({ {modernOnly=true}, {legacyOnly=true} }) do
        local A = M.boot(options)
        hover()
        assert(panel(A).right:GetText() == "炉石")
    end
end)
test("coalescing and visible repeat skip lookup", function()
    local A = M.boot()
    A.Diagnostics.enabled = true
    M.item(GameTooltip, "Hearthstone", 6948)
    assert(#M.queue == 1)
    M.flush()
    for i=1,20 do A.Tooltips:Queue(A.Tooltips.states[GameTooltip]) end
    assert(#M.queue == 1)
    M.flush()
    assert(A.Diagnostics.metrics.lookup.count == 1)
    assert(A.Diagnostics.metrics.repeat_skipped.count == 1)
end)
test("disabled and pvp have no lookup or queued work", function()
    local A = M.boot()
    A.SetEnabled(false)
    for i=1,100 do M.item(GameTooltip, "Hearthstone", 6948) end
    assert(M.loads == 0 and #M.queue == 0 and M.clockCalls == 0)
    A.SetMode("pvp"); A.SetEnabled(true)
    hover()
    assert(M.loads == 0 and panel(A) == nil)
end)
test("old callbacks cannot resurrect disabled or changed content", function()
    local A = M.boot()
    M.item(GameTooltip, "Hearthstone", 6948)
    A.SetEnabled(false)
    M.flush()
    assert(panel(A) == nil and M.loads == 0)
    A.SetEnabled(true)
    M.item(GameTooltip, "Linen Cloth", 2589)
    M.flush()
    assert(panel(A).right:GetText() == "亚麻布")
end)
test("hide, nonitem and missing translation clear owned display", function()
    local A = M.boot()
    hover()
    hover(117, "Tough Jerky")
    assert(not panel(A):IsShown())
    hover()
    -- Cleared content that is not refilled with an item goes on the re-check.
    GameTooltip:Fire("OnTooltipCleared")
    GameTooltip.itemName, GameTooltip.link = nil, nil
    M.flush()
    assert(not panel(A):IsShown())
    M.item(GameTooltip, "Hearthstone", 6948)
    GameTooltip:Hide()
    M.flush()
    assert(not panel(A):IsShown())
end)
test("style and mode changes preserve preferences and refresh", function()
    local A = M.boot()
    hover()
    A.SetSize(24); A.SetColor(0.2, 0.3, 0.4)
    M.flush()
    assert(panel(A).right.fontSize == 24 and panel(A).right.color[1] == 0.2)
    A.SetMode("pvp")
    assert(not panel(A):IsShown())
    A.SetMode("minimal"); M.flush()
    assert(panel(A):IsShown() and A.db.fontSize == 24)
    local saved = WoWFeTranslatorDB
    A = M.boot({saved=saved})
    assert(A.db.mode == "minimal" and A.db.fontSize == 24)
end)
test("damaged settings sanitized and future settings preserved", function()
    local A = M.boot({saved={fontSize=999, fontIndex="bad", color={false,-1,2}, mode="bad"}})
    assert(A.db.fontSize == 30 and A.db.fontIndex == 1 and A.db.color[2] == 0)
    local saved = {schemaVersion=99, marker="preserve"}
    A = M.boot({saved=saved})
    A.SetEnabled(false)
    assert(WoWFeTranslatorDB == saved and saved.enabled == nil)
end)
test("data load failure is bounded and reported", function()
    local A = M.boot({loadFailure=true})
    for i=1,10 do hover() end
    assert(M.loads == 1 and A.Repository.status == "load failed: DISABLED" and not panel(A))
    assert(A.Diagnostics:Report():find("DISABLED"))
end)
test("combat first load deferred, leaving combat refreshes", function()
    local A = M.boot()
    M.combat = true
    hover()
    assert(M.loads == 0)
    M.combat = false
    M.event("PLAYER_REGEN_ENABLED"); M.flush()
    assert(M.loads == 1 and panel(A):IsShown())
end)
test("restricted item values are not parsed", function()
    local A = M.boot()
    M.secret = {}
    M.item(GameTooltip, "Hearthstone", 6948)
    GameTooltip.link = M.secret
    M.flush()
    assert(M.loads == 0)
    M.secret = nil
end)
test("two native tooltips have independent lifetimes", function()
    local A = M.boot()
    hover()
    M.item(ItemRefTooltip, "Linen Cloth", 2589); M.flush()
    GameTooltip:Hide()
    assert(A.Tooltips.states[ItemRefTooltip].panel:IsShown())
    A.SetEnabled(false)
    assert(not A.Tooltips.states[ItemRefTooltip].panel:IsShown())
end)
test("report and bounded samples", function()
    local A = M.boot()
    A.Diagnostics.enabled = true
    for i=1,1000 do A.Diagnostics:Finish("test", A.Diagnostics:Start()) end
    assert(#A.Diagnostics.metrics.test.samples == 256)
    A.UI:Report()
    assert(A.UI.reportText:GetText():find("p95="))
    A.Diagnostics:Reset()
    assert(next(A.Diagnostics.metrics) == nil)
end)
test("content refresh keeps the display without lookup or render", function()
    local A = M.boot()
    A.Diagnostics.enabled = true
    hover()
    local rendered = A.Diagnostics.metrics.render.count
    for i = 1, 5 do
        M.refresh(GameTooltip, "Hearthstone", 6948)
        assert(panel(A):IsShown())
        M.flush()
        assert(panel(A):IsShown())
    end
    assert(A.Diagnostics.metrics.render.count == rendered)
    assert(A.Diagnostics.metrics.lookup.count == 1)
    assert(A.Diagnostics.metrics.repeat_skipped.count == 5)
    assert(A.Diagnostics.metrics.content_cleared.count >= 5)
end)
test("new owner clears at once; refreshed content is re-checked", function()
    local A = M.boot()
    hover()
    GameTooltip:SetOwner(UIParent)
    assert(not panel(A):IsShown())
    hover()
    M.refresh(GameTooltip, "Linen Cloth", 2589); M.flush()
    assert(panel(A):IsShown() and panel(A).right:GetText() == "亚麻布")
    M.refresh(GameTooltip, nil, nil)
    assert(panel(A):IsShown())
    M.flush()
    assert(not panel(A):IsShown())
end)
test("tooltip under a hidden parent is not processed", function()
    local A = M.boot()
    A.Diagnostics.enabled = true
    hover()
    local host = M.widget("host")
    host:Hide()
    GameTooltip:SetParent(host)
    M.item(GameTooltip, "Linen Cloth", 2589); M.flush()
    assert(A.Diagnostics.metrics.lookup.count == 1 and not panel(A):IsShown())
    GameTooltip:SetParent(UIParent)
    M.item(GameTooltip, "Linen Cloth", 2589); M.flush()
    assert(panel(A):IsShown() and panel(A).right:GetText() == "亚麻布")
end)
test("item ID from tooltip data when the link has none", function()
    local A = M.boot()
    M.item(GameTooltip, "Hearthstone", 6948)
    GameTooltip.link = "|Hgarbage|h[Hearthstone]|h"
    M.flush()
    assert(panel(A).right:GetText() == "炉石")
end)
print(string.format("%d runtime tests passed (mock environment, not game validation)", total))
